// Generates public/firebase-messaging-sw.js from the same REACT_APP_FIREBASE_*
// environment variables the rest of the app uses (see src/firebase/config.js).
//
// Why this exists: Create React App only processes files that go through
// webpack (src/**), but a Firebase Messaging service worker must be a
// plain static file served from the site root (so its scope covers the
// whole origin) — it can't import from src/ or read process.env at
// runtime in the browser. Regenerating it here from .env at build/dev time
// means REACT_APP_FIREBASE_* only has to be set in one place instead of
// being duplicated (and manually kept in sync) inside a committed
// public/firebase-messaging-sw.js.
//
// Note: the values written into this file are the public Firebase web
// config (apiKey, appId, etc.) — not secret, safe in a client-side file.
// Runs automatically via the "prestart"/"prebuild" npm scripts.

const fs = require("fs");
const path = require("path");

// CRA loads .env files itself for `react-scripts start`/`build`, but this
// script runs as a separate `node` process one step earlier, so it has to
// load them itself. Mirrors CRA's own precedence (.env.local wins, then
// .env), without requiring a new dependency.
const dotenv = (() => {
  try {
    return require("dotenv");
  } catch {
    return null;
  }
})();

if (dotenv) {
  const root = path.resolve(__dirname, "..");
  const envFiles = [".env.local", ".env"];
  for (const file of envFiles) {
    const fullPath = path.join(root, file);
    if (fs.existsSync(fullPath)) dotenv.config({ path: fullPath });
  }
}

const requiredVars = [
  "REACT_APP_FIREBASE_API_KEY",
  "REACT_APP_FIREBASE_AUTH_DOMAIN",
  "REACT_APP_FIREBASE_PROJECT_ID",
  "REACT_APP_FIREBASE_STORAGE_BUCKET",
  "REACT_APP_FIREBASE_MESSAGING_SENDER_ID",
  "REACT_APP_FIREBASE_APP_ID",
];

const missing = requiredVars.filter((key) => !process.env[key]);

if (missing.length > 0) {
  console.error(
    `[generate-firebase-sw] ERROR: missing ${missing.join(", ")}. ` +
    "The production build cannot continue because Firebase Messaging requires " +
    "a real service worker configuration. Add these REACT_APP_FIREBASE_* variables " +
    "to the frontend deployment environment and rebuild."
  );
  process.exit(1);
}

const config = {
  apiKey: process.env.REACT_APP_FIREBASE_API_KEY,
  authDomain: process.env.REACT_APP_FIREBASE_AUTH_DOMAIN,
  projectId: process.env.REACT_APP_FIREBASE_PROJECT_ID,
  storageBucket: process.env.REACT_APP_FIREBASE_STORAGE_BUCKET,
  messagingSenderId: process.env.REACT_APP_FIREBASE_MESSAGING_SENDER_ID,
  appId: process.env.REACT_APP_FIREBASE_APP_ID,
};

const template = `// AUTO-GENERATED by scripts/generate-firebase-sw.js — do not edit by hand.
// Regenerated from frontend/.env on every \`npm start\` / \`npm run build\`.
// See that script for why this has to be a static file instead of
// importing src/firebase/config.js directly.

importScripts("https://www.gstatic.com/firebasejs/10.13.0/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/10.13.0/firebase-messaging-compat.js");

firebase.initializeApp(${JSON.stringify(config, null, 2)});

const messaging = firebase.messaging();

// Fires for push messages that arrive while no Study2Gate tab has focus
// (backgrounded tab, or the site closed entirely). Foreground delivery
// while a tab IS focused is handled instead by onMessage() in
// src/firebase/messaging.js, which deliberately does not show a native
// notification (see that file for why).
messaging.onBackgroundMessage((payload) => {
  const title = payload.notification?.title || payload.data?.title || "Study2Gate";
  const body = payload.notification?.body || payload.data?.body || "";
  const url = payload.data?.url || "/";

  self.registration.showNotification(title, {
    body,
    icon: "/study2gate-logo.png",
    badge: "/study2gate-logo.png",
    data: { url },
    tag: payload.data?.notificationId || undefined,
  });
});

// Clicking the notification focuses an already-open Study2Gate tab and
// navigates it to the relevant page, instead of always opening a new tab.
self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const targetUrl = event.notification.data?.url || "/";

  event.waitUntil(
    (async () => {
      const clientsList = await clients.matchAll({ type: "window", includeUncontrolled: true });
      const origin = self.location.origin;

      for (const client of clientsList) {
        if (client.url.startsWith(origin)) {
          await client.focus();
          if ("navigate" in client) {
            try {
              await client.navigate(targetUrl);
            } catch {
              // Some browsers restrict cross-origin-looking navigate calls
              // even for same-origin URLs from a SW context; postMessage
              // lets the already-loaded app route client-side instead.
              client.postMessage({ type: "push-notification-click", url: targetUrl });
            }
          }
          return;
        }
      }

      await clients.openWindow(origin + targetUrl);
    })()
  );
});
`;

const outputPath = path.resolve(__dirname, "..", "public", "firebase-messaging-sw.js");
fs.writeFileSync(outputPath, template, "utf8");
console.log(`[generate-firebase-sw] Wrote ${outputPath}`);
